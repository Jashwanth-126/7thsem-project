import { useState } from "react";
import toast from "react-hot-toast";
import jsQR from "jsqr";
import API from "../services/api";

function QRScannerModal({ auction, onScan, onClose, refresh, mode }) {
  const [loading, setLoading] = useState(false);
  const [scanError, setScanError] = useState("");

  const isTraceabilityMode = mode === "traceability" || !!onScan || !auction;

  const verifyDelivery = async (token) => {
    try {
      setLoading(true);
      setScanError("");
      
      const response = await API.post("/api/payment/dealer/verify-delivery-qr", {
        auction_id: auction?.auction_id || auction?.id,
        token: token
      });
      
      if(response.data.success) {
        toast.success("Delivery Verified Successfully!");
        if (refresh) refresh();
        onClose();
      }
    } catch (error) {
      console.error(error);
      setScanError(error.response?.data?.message || "Verification Failed");
      toast.error(error.response?.data?.message || "Verification Failed");
    } finally {
      setLoading(false);
    }
  };

  const handleImageUpload = (e) => {
    const file = e.target.files[0];
    if (!file) return;

    setScanError("");
    setLoading(true);

    const reader = new FileReader();
    reader.onload = (event) => {
      const img = new Image();
      img.onload = () => {
        const canvas = document.createElement("canvas");
        canvas.width = img.width;
        canvas.height = img.height;
        const ctx = canvas.getContext("2d");
        ctx.drawImage(img, 0, 0, img.width, img.height);
        
        try {
          const imageData = ctx.getImageData(0, 0, canvas.width, canvas.height);
          const code = jsQR(imageData.data, imageData.width, imageData.height);
          
          if (code) {
            console.log("QR Data:", code.data);
            
            if (isTraceabilityMode && onScan) {
              toast.success("Crop Traceability QR Code Scanned!");
              onScan(code.data);
              return;
            }

            // Expected format for delivery: auction_id:123,crop_id:456,...,token:abc-123
            const parts = code.data.split(",");
            let token = null;
            
            for (let part of parts) {
              const [key, value] = part.split(":");
              if (key === "token") {
                token = value;
              }
            }
            
            if (token) {
              toast.success("QR Scanned! Verifying...");
              verifyDelivery(token);
            } else {
              setScanError("Invalid Delivery QR Code: Missing verification token");
              setLoading(false);
            }
          } else {
            setScanError("Could not detect a QR code in the uploaded image. Please ensure the QR image is clear.");
            setLoading(false);
          }
        } catch (err) {
          setScanError("Error processing image.");
          setLoading(false);
        }
      };
      img.src = event.target.result;
    };
    reader.readAsDataURL(file);
  };

  return (
    <div className="fixed inset-0 bg-black/60 flex justify-center items-center z-50 p-4 backdrop-blur-sm">
      <div className="bg-white rounded-3xl p-8 w-full max-w-lg shadow-2xl">
        <h2 className={`text-3xl font-bold mb-4 ${isTraceabilityMode ? 'text-emerald-700' : 'text-blue-700'}`}>
          {isTraceabilityMode ? "Scan Crop Traceability QR" : "Verify Delivery QR"}
        </h2>
        
        <div className={`mb-6 p-6 rounded-2xl border ${isTraceabilityMode ? 'bg-emerald-50 border-emerald-100' : 'bg-blue-50 border-blue-100'}`}>
          <p className="text-gray-700 mb-4 text-base md:text-lg">
            {isTraceabilityMode
              ? "Please upload or select a Crop QR Code image to automatically scan its Traceability ID and view complete farm-to-fork journey details."
              : "Please upload the Delivery QR Code image that was generated by the farmer when dispatching the crops."
            }
          </p>
          
          <label className={`block w-full cursor-pointer bg-white border-2 border-dashed p-8 rounded-2xl text-center transition-colors ${isTraceabilityMode ? 'border-emerald-400 hover:bg-emerald-50' : 'border-blue-400 hover:bg-blue-50'}`}>
            <span className={`font-bold text-xl mb-2 block ${isTraceabilityMode ? 'text-emerald-600' : 'text-blue-600'}`}>
              {loading ? "Scanning QR Code..." : "Click to Upload QR Image"}
            </span>
            <span className="text-xs text-gray-400 block">Supports PNG, JPG, JPEG</span>
            <input 
              type="file" 
              accept="image/*" 
              className="hidden" 
              onChange={handleImageUpload}
              disabled={loading}
            />
          </label>
        </div>

        {scanError && (
          <div className="bg-red-100 text-red-700 p-4 rounded-xl mb-6 font-semibold text-sm border border-red-300">
            ❌ {scanError}
          </div>
        )}

        <div className="flex justify-end">
          <button
            onClick={onClose}
            className="bg-gray-500 hover:bg-gray-600 text-white px-8 py-3 rounded-2xl font-bold transition-colors text-sm"
          >
            Cancel
          </button>
        </div>
      </div>
    </div>
  );
}

export default QRScannerModal;
